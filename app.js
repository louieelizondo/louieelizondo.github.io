let palIndex = 0;
let palQuery = "";

function renderPalette() {
  const list = $("#palette-list");
  if (!list) return;
  const items = commands().filter((c) =>
    c.label.toLowerCase().includes(palQuery.toLowerCase())
  );
  list.innerHTML = items
    .map(
      (c, i) =>
        `<li><button type="button" data-id="${c.id}" class="${i === palIndex ? "active" : ""}">${c.label}<kbd>${c.hint}</kbd></button></li>`
    )
    .join("");
  list.querySelectorAll("button").forEach((btn) => {
    btn.addEventListener("click", () => {
      const cmd = commands().find((c) => c.id === btn.dataset.id);
      closePalette();
      cmd?.run();
    });
  });
}

function openPalette() {
  palQuery = "";
  palIndex = 0;
  $("#palette-input").value = "";
  renderPalette();
  $(".overlay").classList.add("open");
  $("#palette-input").focus();
}

function closePalette() {
  $(".overlay").classList.remove("open");
}

function go(hash) {
  const el = $(hash);
  if (!el) return;
  el.scrollIntoView({ behavior: "smooth", block: "start" });
  history.replaceState(null, "", hash);
  highlightStation(hash);
}

function highlightStation(hash) {
  $$(".station-tab").forEach((tab) => {
    tab.setAttribute("aria-current", String(tab.getAttribute("href") === hash));
  });
}

function bindMagnetic() {
  if (window.matchMedia("(pointer: coarse), (prefers-reduced-motion: reduce)").matches) return;
  $$(".tile, .work-card, .civic-card").forEach((card) => {
    card.addEventListener("mousemove", (e) => {
      const r = card.getBoundingClientRect();
      const x = (e.clientX - r.left) / r.width - 0.5;
      const y = (e.clientY - r.top) / r.height - 0.5;
      card.style.transform = `perspective(900px) rotateY(${x * 6}deg) rotateX(${-y * 6}deg)`;
    });
    card.addEventListener("mouseleave", () => {
      card.style.transform = "";
    });
  });
}

async function githubCalendar() {
  const graph = $("#contrib-graph");
  const totalEl = $("#contrib-total");
  const legend = $("#contrib-legend");
  const username = "louieelizondo";
  const colors = ["#241c16", "#5a2a1e", "#8f3a28", "#c4452d", "#e24a2f"];
  try {
    const res = await fetch(`https://github-contributions-api.jogruber.de/v4/${username}?y=last`);
    if (!res.ok) throw new Error("api");
    const data = await res.json();
    const total = data.total?.lastYear || data.total?.last || Object.values(data.total || {}).pop() || 0;
    window.__ghReady = true;
    totalEl.innerHTML = `<span style="color:var(--chile)">${total}</span> ${lang === "es" ? "contribuciones este año" : "contributions this year"}`;
    const contributions = data.contributions || [];
    const cellSize = 11;
    const cellGap = 3;
    const step = cellSize + cellGap;
    const weeks = 53;
    const days = 7;
    const labelW = 28;
    const svgW = labelW + weeks * step;
    const monthLabelH = 18;
    const svgH = monthLabelH + days * step;
    const months = lang === "es"
      ? ["Ene", "Feb", "Mar", "Abr", "May", "Jun", "Jul", "Ago", "Sep", "Oct", "Nov", "Dic"]
      : ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
    let svg = `<svg width="100%" viewBox="0 0 ${svgW} ${svgH}" xmlns="http://www.w3.org/2000/svg" style="max-width:${svgW}px">`;
    let lastMonth = -1;
    const flat = contributions.flat();
    flat.forEach((day, i) => {
      const d = new Date(day.date);
      const weekIdx = Math.floor(i / 7);
      const dayIdx = i % 7;
      if (dayIdx === 0) {
        const m = d.getMonth();
        if (m !== lastMonth) {
          lastMonth = m;
          svg += `<text x="${labelW + weekIdx * step}" y="12" fill="#9a8b7a" font-size="9" font-family="IBM Plex Mono, monospace">${months[m]}</text>`;
        }
      }
    });
    ["Mon", "", "Wed", "", "Fri", "", ""].forEach((label, i) => {
      if (label) {
        svg += `<text x="0" y="${monthLabelH + i * step + cellSize - 2}" fill="#9a8b7a" font-size="8" font-family="IBM Plex Mono, monospace">${label}</text>`;
      }
    });
    flat.forEach((day, i) => {
      const weekIdx = Math.floor(i / 7);
      const dayIdx = i % 7;
      const x = labelW + weekIdx * step;
      const y = monthLabelH + dayIdx * step;
      const level = Math.min(day.level || 0, 4);
      svg += `<rect x="${x}" y="${y}" width="${cellSize}" height="${cellSize}" rx="2" fill="${colors[level]}"><title>${day.date}: ${day.count || 0}</title></rect>`;
    });
    svg += "</svg>";
    graph.innerHTML = svg;
    legend.style.display = "flex";
  } catch {
    graph.innerHTML = `<a href="https://github.com/${username}" target="_blank" rel="noreferrer">GitHub →</a>`;
    totalEl.textContent = "GitHub";
  }
}

function bindKeys() {
  document.addEventListener("keydown", (e) => {
    const inField = ["INPUT", "TEXTAREA"].includes(document.activeElement?.tagName);
    if ((e.metaKey || e.ctrlKey) && e.key.toLowerCase() === "k") {
      e.preventDefault();
      $(".overlay").classList.contains("open") ? closePalette() : openPalette();
      return;
    }
    if (e.key === "Escape") {
      closePalette();
      return;
    }
    if ($(".overlay").classList.contains("open")) {
      const items = $$("#palette-list button");
      if (e.key === "ArrowDown") {
        e.preventDefault();
        palIndex = Math.min(palIndex + 1, items.length - 1);
        renderPalette();
      }
      if (e.key === "ArrowUp") {
        e.preventDefault();
        palIndex = Math.max(palIndex - 1, 0);
        renderPalette();
      }
      if (e.key === "Enter") {
        e.preventDefault();
        items[palIndex]?.click();
      }
      return;
    }
    if (inField) return;
    const map = { 1: "#identity", 2: "#kitchen", 3: "#chamber", 4: "#code", 5: "#now" };
    if (map[e.key]) {
      e.preventDefault();
      go(map[e.key]);
    }
    if (e.key.toLowerCase() === "l") setLang(lang === "es" ? "en" : "es");
    if (e.key === "/") {
      e.preventDefault();
      openPalette();
    }
  });
}

document.addEventListener("DOMContentLoaded", () => {
  applyLang();
  tickClock();
  setInterval(tickClock, 1000);
  bindMagnetic();
  bindKeys();
  githubCalendar();

  $("#cmd-open")?.addEventListener("click", openPalette);
  $("#overlay")?.addEventListener("click", (e) => {
    if (e.target.id === "overlay") closePalette();
  });
  $("#palette-input")?.addEventListener("input", (e) => {
    palQuery = e.target.value;
    palIndex = 0;
    renderPalette();
  });
  $$(".lang-switch button").forEach((btn) => {
    btn.addEventListener("click", () => setLang(btn.dataset.lang));
  });
  $$(".station-tab").forEach((tab) => {
    tab.addEventListener("click", (e) => {
      e.preventDefault();
      go(tab.getAttribute("href"));
    });
  });

  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        highlightStation("#" + entry.target.id);
      });
    },
    { rootMargin: "-40% 0px -50% 0px", threshold: 0.1 }
  );
  ["identity", "kitchen", "chamber", "code", "now"].forEach((id) => {
    const el = document.getElementById(id);
    if (el) observer.observe(el);
  });
});
