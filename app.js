const $ = (sel, root = document) => root.querySelector(sel);
const $$ = (sel, root = document) => [...root.querySelectorAll(sel)];

function detectLang() {
  const saved = localStorage.getItem("le-lang");
  if (saved === "en" || saved === "es") return saved;
  return navigator.language?.toLowerCase().startsWith("es") ? "es" : "en";
}

let lang = detectLang();

function applyLang() {
  const t = copy[lang];
  document.documentElement.lang = lang;
  $$("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (t[key]) el.textContent = t[key];
  });
  $$("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (t[key]) el.setAttribute("placeholder", t[key]);
  });
  $$(".lang-switch button").forEach((btn) => {
    btn.setAttribute("aria-pressed", String(btn.dataset.lang === lang));
  });
  localStorage.setItem("le-lang", lang);
  renderPalette();
  if (window.__ghReady) githubCalendar();
}

function setLang(next) {
  lang = next;
  applyLang();
}

function tickClock() {
  const now = new Date();
  const time = new Intl.DateTimeFormat(lang === "es" ? "es-MX" : "en-US", {
    timeZone: "America/Chihuahua",
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    hour12: false,
  }).format(now);
  const date = new Intl.DateTimeFormat(lang === "es" ? "es-MX" : "en-US", {
    timeZone: "America/Chihuahua",
    weekday: "short",
    day: "numeric",
    month: "short",
  }).format(now);
  const el = $("#clock-time");
  const d = $("#clock-date");
  if (el) el.textContent = time;
  if (d) d.textContent = date;
}

